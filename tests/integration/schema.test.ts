// schema.sql is generated from the migrations for reference. This test fails when it is out
// of date; run `npm run db:schema` to update it.

import Database from 'better-sqlite3';
import { expect, it } from 'vitest';
import { migrate, schemaVersion } from '@/server/db/migrate';

// Order in the file: reference data, application state, derived data, operational tables.
const TABLE_ORDER = [
  'rubrics', 'rubric_criteria', 'rubric_levels',
  'sessions', 'essays', 'topics', 'topic_assignments', 'grades', 'benchmarks', 'teacher_highlights',
  'essay_similarities', 'essay_summaries', 'essay_embeddings', 'ai_assessments', 'topic_models',
  'pipeline_runs', 'action_logs',
];

/** Re-indents a CREATE statement taken from a migration's template string. */
function tidy(sql: string): string {
  const [first, ...rest] = sql.split('\n');
  const indent = (l: string) => l.length - l.trimStart().length;
  const body = rest.filter((l) => l.trim() && !l.trim().startsWith(')'));
  const cut = Math.max(0, Math.min(...body.map(indent), Infinity) - 2);
  const lines = rest.map((l) => (l.trim().startsWith(')') ? l.trim() : l.slice(Math.min(cut, indent(l)))));
  return [first.trim(), ...lines].join('\n').trimEnd();
}

it('schema.sql matches the schema the migrations create', async () => {
  const db = new Database(':memory:');
  migrate(db);

  const objects = db.prepare(`
    SELECT type, name, tbl_name, sql FROM sqlite_master
    WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'
  `).all() as { type: string; name: string; tbl_name: string; sql: string }[];
  const rank = (table: string) => {
    const i = TABLE_ORDER.indexOf(table);
    return i === -1 ? TABLE_ORDER.length : i;
  };
  const typeRank = { table: 0, view: 1, index: 2, trigger: 3 } as Record<string, number>;
  objects.sort((a, b) => typeRank[a.type] - typeRank[b.type]
    || rank(a.tbl_name) - rank(b.tbl_name) || a.name.localeCompare(b.name));

  // New tables must be added to TABLE_ORDER.
  const unordered = objects.filter((o) => o.type === 'table' && rank(o.name) === TABLE_ORDER.length);
  expect(unordered.map((o) => o.name)).toEqual([]);

  const text = [
    `-- Schema version ${schemaVersion(db)}, as created by the migrations in src/server/db/migrations/.`,
    '-- Generated by `npm run db:schema`; do not edit. Change the schema with a new migration.',
    '',
    ...objects.map((o) => `${tidy(o.sql)};\n`),
  ].join('\n');

  await expect(text).toMatchFileSnapshot('../../src/server/db/schema.sql');
});
